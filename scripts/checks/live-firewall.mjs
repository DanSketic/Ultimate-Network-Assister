import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
/*
 * Checks the parser that turns a gateway's loaded ruleset into verified claims.
 *
 * This is the one place in the application allowed to move a statement from
 * "not verified" to "measured", so what it must not do matters more than what
 * it must: a chain it cannot read has to yield nothing rather than a guess, and
 * a rule it cannot find has to stay unverified rather than become absent.
 *
 * The sample below keeps the exact shape of a measured UDM dump — chain names,
 * rule pairing, the log prefixes, the unconditional final rule — with generic
 * addresses, because the structure is what is under test and a real estate's
 * layout has no business in a published repository.
 */
import { build } from 'esbuild';
import { rmSync } from 'node:fs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url)).replace(/\\/g, '/').replace(/\/$/, '');
const OUT = join(tmpdir(), 'live-fw-bundle-' + process.pid + '.mjs').replace(/\\/g, '/');

await build({
  entryPoints: [`${ROOT}/src/survey/liveFirewall.ts`],
  bundle: true,
  format: 'esm',
  outfile: OUT,
  platform: 'neutral',
  alias: { '@': `${ROOT}/src` },
  logLevel: 'error',
});
const { parseLiveFirewall, parseRoutableV6, readLiveEstate, combinedReachability, reachability, zoneOfVlan } =
  await import(`file://${OUT}`);

let failures = 0;
const check = (name, ok, detail = '') => {
  console.log(`${ok ? 'ok  ' : 'FAIL'}  ${name}${detail ? '   ' + detail : ''}`);
  if (!ok) failures += 1;
};

/** The 20-digit comment the gateway puts on the last rule of every zone chain. */
const LAST = '00000001097364144127';
const log = (id, kind, action) =>
  `-m state --state NEW -m limit --limit 50/sec -j NFLOG --nflog-prefix  "${id};${kind};${action}" --nflog-group 1`;

const SAMPLE = `# Generated by iptables-save v1.8.7
*nat
:PREROUTING ACCEPT [0:0]
-A PREROUTING -j UBIOS_PREROUTING_JUMP
COMMIT
# Generated by iptables-save v1.8.7
*filter
:INPUT ACCEPT [0:0]
:UBIOS_FORWARD_IN_USER - [0:0]
:UBIOS_LAN_GUEST_USER - [0:0]
:UBIOS_GUEST_LAN_USER - [0:0]
:UBIOS_LAN_LAN_USER - [0:0]
:UBIOS_GUEST_GUEST_USER - [0:0]
:UBIOS_LAN_DMZ_USER - [0:0]
:UBIOS_DMZ_LAN_USER - [0:0]
:UBIOS_LAN_IN_USER - [0:0]
:UBIOS_FALLTHROUGH_LAN_USER - [0:0]

-A UBIOS_FORWARD_IN_USER -i br0 ${log('aaaa0000000000000000d001', 'PREDEFINED_FIREWALL_RULE', 'NONE')}
-A UBIOS_FORWARD_IN_USER -i br0 -m comment --comment 00000001095216690481 -j UBIOS_LAN_IN_USER
-A UBIOS_FORWARD_IN_USER -i br10 -m comment --comment 00000001095216690482 -j UBIOS_LAN_IN_USER
-A UBIOS_FORWARD_IN_USER -i br20 -m comment --comment 00000001095216690483 -j UBIOS_GUEST_IN_USER
-A UBIOS_FORWARD_IN_USER -i br30 -m comment --comment 00000001095216690484 -j UBIOS_DMZ_IN_USER
-A UBIOS_FORWARD_IN_USER -i wgsrv+ -m comment --comment 00000001095216690485 -j UBIOS_VPN_IN_USER

-A UBIOS_LAN_IN_USER -m set --match-set UBIOS_GUEST_subnets dst -m comment --comment 00000001095216690486 -j UBIOS_LAN_GUEST_USER

-A UBIOS_LAN_GUEST_USER ${log('bbbb0000000000000000d002', 'PREDEFINED_FIREWALL_RULE', 'ACCEPT')}
-A UBIOS_LAN_GUEST_USER -m comment --comment ${LAST} -j ACCEPT

-A UBIOS_GUEST_LAN_USER -m conntrack --ctstate RELATED,ESTABLISHED -m comment --comment 00000001095216690480 -j ACCEPT
-A UBIOS_GUEST_LAN_USER ${log('cccc0000000000000000d003', 'PREDEFINED_FIREWALL_RULE', 'DROP')}
-A UBIOS_GUEST_LAN_USER -m comment --comment ${LAST} -j DROP

-A UBIOS_GUEST_GUEST_USER -m comment --comment ${LAST} -j DROP

-A UBIOS_LAN_LAN_USER -m set --match-set UBIOS_policy_src_net_10 src -m set --match-set UBIOS_policy_dst_net_10 dst ${log('dddd0000000000000000d004', 'FIREWALL_POLICY', 'DROP')}
-A UBIOS_LAN_LAN_USER -m set --match-set UBIOS_policy_src_net_10 src -m set --match-set UBIOS_policy_dst_net_10 dst -m comment --comment 00000001095216670480 -j DROP
-A UBIOS_LAN_LAN_USER -m comment --comment ${LAST} -j ACCEPT

-A UBIOS_LAN_DMZ_USER -m comment --comment ${LAST} -j ACCEPT
-A UBIOS_DMZ_LAN_USER -m conntrack --ctstate RELATED,ESTABLISHED -m comment --comment 00000001095216690480 -j ACCEPT
-A UBIOS_DMZ_LAN_USER -m comment --comment ${LAST} -j DROP

-A UBIOS_FALLTHROUGH_LAN_USER -p tcp -m tcp --dport 443 -m comment --comment 00000001095216670480 -j ACCEPT
COMMIT
`;

const live = parseLiveFirewall(SAMPLE);

/* ------------------------------------------------------ zones and bridges */

check('the ruleset is recognised', live.recognised === true);
check(
  'IN is not read as a zone',
  !live.zones.includes('IN') && !live.zones.includes('FORWARD'),
  live.zones.join(','),
);
check(
  'the zones are the real ones',
  ['LAN', 'GUEST', 'DMZ', 'FALLTHROUGH'].every((z) => live.zones.includes(z)),
  live.zones.join(','),
);
check('br0 is the untagged network', zoneOfVlan(live, null) === 'LAN');
check('br20 is the guest zone', zoneOfVlan(live, 20) === 'GUEST');
check('br30 is the DMZ', zoneOfVlan(live, 30) === 'DMZ');
check(
  'a VLAN the ruleset never mentioned has no zone',
  zoneOfVlan(live, 99) === null,
  String(zoneOfVlan(live, 99)),
);

/* ----------------------------------------------------------- the verdicts */

const verdict = (from, to) => reachability(live, from, to)?.verdict ?? 'unknown';

check('LAN to guest is open', verdict(null, 20) === 'allow', verdict(null, 20));
check('guest to LAN is blocked', verdict(20, null) === 'block', verdict(20, null));
check('guest to guest is blocked', verdict(20, 20) === 'block', verdict(20, 20));
check('LAN to LAN is limited by a policy', verdict(null, 10) === 'limited', verdict(null, 10));
check('LAN to DMZ is open', verdict(null, 30) === 'allow', verdict(null, 30));
check('DMZ to LAN is blocked', verdict(30, null) === 'block', verdict(30, null));

check(
  'a blocked pair that lets replies back says so',
  reachability(live, 20, null)?.repliesOnly === true,
);
check(
  'an established-only accept is not counted as an exception',
  reachability(live, 20, null)?.exceptions === 0,
  String(reachability(live, 20, null)?.exceptions),
);
check(
  'a real exception is counted',
  reachability(live, null, 10)?.exceptions === 1,
  String(reachability(live, null, 10)?.exceptions),
);

/* ----------------------------------------- what it must refuse to conclude */

check(
  'a chain with no unconditional last rule yields nothing',
  !live.pairs.has('FALLTHROUGH>LAN'),
  'FALLTHROUGH>LAN was decided anyway',
);
check(
  'an unread pair is absent rather than guessed',
  reachability(live, 99, null) === null && reachability(live, null, 99) === null,
);

const empty = parseLiveFirewall('');
check('no text means nothing measured', empty.recognised === false && empty.pairs.size === 0);

const foreign = parseLiveFirewall('*filter\n:INPUT ACCEPT [0:0]\n-A INPUT -i lo -j ACCEPT\nCOMMIT\n');
check(
  'a non-UniFi ruleset yields no zones',
  foreign.recognised === false && foreign.pairs.size === 0 && foreign.zones.length === 0,
);

/* -------------------------------------------------------------- rule ids */

check(
  'ids are read off the log lines',
  live.ruleIds.has('dddd0000000000000000d004') && live.ruleIds.has('cccc0000000000000000d003'),
  [...live.ruleIds].join(','),
);
check(
  'the ordering comment is not mistaken for an id',
  !live.ruleIds.has(LAST) && ![...live.ruleIds].some((id) => /^\d+$/.test(id)),
);
check(
  'a rule with logging off leaves no id, and none is invented',
  live.ruleIds.size === 4,
  `${live.ruleIds.size} ids`,
);

/* ------------------------------------------------------------ robustness */

for (const [name, text] of [
  ['truncated mid-line', SAMPLE.slice(0, SAMPLE.length / 2)],
  ['CRLF line endings', SAMPLE.replace(/\n/g, '\r\n')],
  ['no trailing newline', SAMPLE.trimEnd()],
]) {
  let ok = true;
  try {
    const parsed = parseLiveFirewall(text);
    // Whatever it manages to read, it must never invent a zone called IN.
    ok = !parsed.zones.includes('IN');
  } catch (e) {
    ok = false;
  }
  check(`survives ${name}`, ok);
}

const crlf = parseLiveFirewall(SAMPLE.replace(/\n/g, '\r\n'));
check(
  'CRLF parses identically',
  crlf.pairs.size === live.pairs.size && crlf.ruleIds.size === live.ruleIds.size,
  `${crlf.pairs.size} vs ${live.pairs.size}`,
);

/* ============================================================ IPv6 =========
 *
 * The comparison exists for one case: IPv4 separates two networks, IPv6 does
 * not, and both ends carry a routable IPv6 address — so the separation is not
 * one. Everything else these assertions do is guard the ways that conclusion
 * can be reached wrongly, because a false leak report is worse than none: it
 * sends someone looking for a hole that is not there.
 */

const ADDRS = `lo               UNKNOWN        127.0.0.1/8 ::1/128
br0              UP             192.0.2.1/24 2001:db8:1::1/64 fe80::1/64
br10             UP             192.0.2.10/24 fe80::10/64
br20             UP             198.51.100.1/24 2001:db8:2::1/64 fe80::20/64
br30             UP             203.0.113.1/24 fe80::30/64
`;

const v6 = parseRoutableV6(ADDRS);
check('a routable IPv6 address counts', v6.has('br0') && v6.has('br20'), [...v6].join(','));
check(
  'link-local alone does not count as IPv6 reachability',
  !v6.has('br10') && !v6.has('br30'),
  [...v6].join(','),
);
check('loopback is not an interface for this', !v6.has('lo'));
check(
  'an aliased name is read without the alias',
  parseRoutableV6('br7@if3  UP  2001:db8::1/64\n').has('br7'),
);

/** The IPv6 table with the zone system entirely absent, and forwarding open. */
const V6_UNFILTERED = `*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
COMMIT
`;
/** The same, but nothing is forwarded at all. */
const V6_CLOSED = V6_UNFILTERED.replace(':FORWARD ACCEPT', ':FORWARD DROP');

check(
  'the filter FORWARD policy is read',
  parseLiveFirewall(V6_UNFILTERED).forwardPolicy === 'accept' &&
    parseLiveFirewall(V6_CLOSED).forwardPolicy === 'drop',
);
check(
  "the mangle table's FORWARD policy is not mistaken for it",
  parseLiveFirewall('*mangle\n:FORWARD ACCEPT [0:0]\nCOMMIT\n').forwardPolicy === null,
);

const verdictOf = (estate, from, to) => combinedReachability(estate, from, to);

/* --- IPv4 blocks, IPv6 is wide open, and both ends carry IPv6: a leak ---- */

const leaky = readLiveEstate(SAMPLE, V6_UNFILTERED, ADDRS);
const guestToLan = verdictOf(leaky, 20, null);
check('the leak is found', guestToLan?.leak === true, JSON.stringify(guestToLan));
check('and the cell stops claiming blocked', guestToLan?.verdict === 'limited', guestToLan?.verdict);
check('both families are named in the answer', guestToLan?.scope === 'both');
check(
  'IPv4 is still reported as what it says',
  guestToLan?.v4 === 'block' && guestToLan?.v6 === 'allow',
);

/* --- the same ruleset where IPv6 does not reach one end: not a leak ------ */

const dmzToLan = verdictOf(leaky, 30, null);
check(
  'no IPv6 on one end means no leak',
  dmzToLan?.leak === false && dmzToLan?.verdict === 'block',
  JSON.stringify(dmzToLan),
);
check('and the answer says why it did not compare', dmzToLan?.scope === 'v4NoV6Here');

/* --- IPv6 present but forwarding closed: the IPv4 verdict stands --------- */

const tight = readLiveEstate(SAMPLE, V6_CLOSED, ADDRS);
check(
  'a closed IPv6 forward is not a leak',
  verdictOf(tight, 20, null)?.leak === false &&
    verdictOf(tight, 20, null)?.verdict === 'block',
  JSON.stringify(verdictOf(tight, 20, null)),
);
check(
  'an allowed pair stays allowed when IPv6 blocks it, but is limited',
  verdictOf(tight, null, 20)?.verdict === 'limited' &&
    verdictOf(tight, null, 20)?.leak === false,
  JSON.stringify(verdictOf(tight, null, 20)),
);

/* --- IPv6 never read: fall back to IPv4 and say so, never guess --------- */

const v4only = readLiveEstate(SAMPLE, '', ADDRS);
check(
  'no IPv6 dump means the IPv4 verdict, labelled',
  v4only.v6.read === false &&
    verdictOf(v4only, 20, null)?.scope === 'v4only' &&
    verdictOf(v4only, 20, null)?.verdict === 'block' &&
    verdictOf(v4only, 20, null)?.leak === false,
  JSON.stringify(verdictOf(v4only, 20, null)),
);

/* --- addresses never read: no leak may be claimed ----------------------- */

const noAddrs = readLiveEstate(SAMPLE, V6_UNFILTERED, '');
check(
  'without addresses no leak is claimed',
  verdictOf(noAddrs, 20, null)?.leak === false &&
    verdictOf(noAddrs, 20, null)?.verdict === 'block',
  JSON.stringify(verdictOf(noAddrs, 20, null)),
);

/* --- an IPv6 table that does carry zone chains -------------------------- */

const V6_ZONED = `*filter
:FORWARD DROP [0:0]
:UBIOS_FORWARD_IN_USER - [0:0]
:UBIOS_GUEST_LAN_USER - [0:0]
-A UBIOS_FORWARD_IN_USER -i br0 -m comment --comment 1 -j UBIOS_LAN_IN_USER
-A UBIOS_FORWARD_IN_USER -i br20 -m comment --comment 2 -j UBIOS_GUEST_IN_USER
-A UBIOS_GUEST_LAN_USER -m comment --comment ${LAST} -j ACCEPT
COMMIT
`;
const zonedV6 = readLiveEstate(SAMPLE, V6_ZONED, ADDRS);
check(
  'an IPv6 zone chain that disagrees is a leak',
  verdictOf(zonedV6, 20, null)?.leak === true &&
    verdictOf(zonedV6, 20, null)?.v6 === 'allow',
  JSON.stringify(verdictOf(zonedV6, 20, null)),
);
check(
  'the IPv6 chain is preferred over the family default',
  // FORWARD is DROP here, so falling back to it would have said 'block'.
  verdictOf(zonedV6, 20, null)?.v6 === 'allow',
);

/* --- a pair IPv4 never decided stays undecided, whatever IPv6 says ------ */

check(
  'IPv6 alone cannot decide a pair',
  combinedReachability(leaky, 99, null) === null,
);

rmSync(OUT, { force: true });
console.log(failures === 0 ? '\nOK' : `\n${failures} FAILED`);
process.exit(failures === 0 ? 0 : 1);
